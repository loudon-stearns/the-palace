"""Write palace.mplstyle from the Loudon Live Design System's own tokens.

The style holds no palette of its own: it is generated from
_ops/loudon-live/design-system/colors_and_type.css, the way the Observable Plot
wrapper (palace-plot-defaults.js) reads tokens at call time. Same choices as that
wrapper: the skin's ground, chart text in fg-3, one mono face for every numeral
(JetBrains Mono), a frame in the border token; series colours from the
categorical set cat-1..cat-6.

  python3 Shop/Matplotlib/palace_mplstyle.py                 # Graphite (the default skin)
  python3 Shop/Matplotlib/palace_mplstyle.py skin-drafting   # a named skin's overrides on top
  python3 Shop/Matplotlib/palace_mplstyle.py --out path.mplstyle

Then, in a figure script:  plt.style.use("Shop/Matplotlib/palace.mplstyle")
Born 2026-11-14 at the Matplotlib card check; the smallest honest version.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CSS = HERE.parents[1] / "_ops/loudon-live/design-system/colors_and_type.css"


def tokens(skin=None):
    css = CSS.read_text()
    root = re.search(r":root\s*\{(.*?)\n\}", css, re.S).group(1)
    t = dict(re.findall(r"--([\w-]+):\s*([^;]+);", root))
    if skin:
        block = re.search(r"\." + re.escape(skin) + r"\b[^{]*\{(.*?)\}", css, re.S)
        if not block:
            sys.exit(f"no skin .{skin} in {CSS}")
        t.update(dict(re.findall(r"--([\w-]+):\s*([^;]+);", block.group(1))))
    return {k: v.strip() for k, v in t.items()}


def hexonly(v):
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", v):
        sys.exit(f"token value {v!r} is not a 6-digit hex; refusing to guess a colour")
    return v[1:]


def style(t):
    cyc = ", ".join(f"'{hexonly(t[f'cat-{i}'])}'" for i in range(1, 7))
    bg, fg1, fg3, border = (hexonly(t[k]) for k in ("bg", "fg-1", "fg-3", "border"))
    return f"""# palace.mplstyle — generated by palace_mplstyle.py from colors_and_type.css; do not edit by hand
figure.facecolor: {bg}
axes.facecolor: {bg}
savefig.facecolor: {bg}
axes.edgecolor: {border}
axes.labelcolor: {fg3}
axes.titlecolor: {fg1}
axes.prop_cycle: cycler('color', [{cyc}])
axes.grid: True
grid.color: {border}
grid.linewidth: 0.5
grid.alpha: 0.6
xtick.color: {fg3}
ytick.color: {fg3}
text.color: {fg1}
legend.frameon: False
legend.labelcolor: {fg3}
font.family: monospace
font.monospace: JetBrains Mono, DejaVu Sans Mono
font.size: 9
axes.titlesize: 11
lines.linewidth: 1.4
svg.fonttype: none
svg.hashsalt: palace
"""


if __name__ == "__main__":
    args = sys.argv[1:]
    out = HERE / "palace.mplstyle"
    if "--out" in args:
        i = args.index("--out"); out = Path(args[i + 1]); del args[i:i + 2]
    skin = args[0] if args else None
    out.write_text(style(tokens(skin)))
    print(f"wrote {out} ({skin or 'Graphite, the default skin'})")
