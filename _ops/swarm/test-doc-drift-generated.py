#!/usr/bin/env python3
"""Sandbox test for lint-doc-drift.py's generated-block check (E4/W3). The Shop's roster is
computed by Shop/Maker/build-roster.mjs, so a session that moves a Specialist into Shop/
without re-running it leaves the block stale. The check must flag that as an error, pass
along the builder's member-of warning, clear once the builder has run, and stay silent on
a root that has no builder.

Run:  python3 _ops/swarm/test-doc-drift-generated.py"""
import os, shutil, subprocess, sys, tempfile

SWARM = os.path.dirname(os.path.abspath(__file__))  # this file lives in _ops/swarm/
PALACE = os.path.normpath(os.path.join(SWARM, "..", ".."))
BUILDER = os.path.join("Shop", "Maker", "build-roster.mjs")
ROOT = tempfile.mkdtemp(prefix="palace-generated-")
START = "<!-- ROSTER:START — generated by Shop/Maker/build-roster.mjs; do not edit by hand -->"


def w(rel, content):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(content)


def lint():
    r = subprocess.run([sys.executable, os.path.join(SWARM, "lint-doc-drift.py"), ROOT],
                       capture_output=True, text=True)
    found = sorted(l.strip() for l in r.stdout.splitlines() if l.strip()[:2] in ("E4", "W3"))
    return r.returncode, found


w("CLAUDE.md", "# Claude\n\n## Ceremony Triggers\n\n| Say | Ceremony |\n|---|---|\n")
os.makedirs(os.path.join(ROOT, "Shop", "Maker"))
shutil.copy(os.path.join(PALACE, BUILDER), os.path.join(ROOT, BUILDER))
w("Shop/Alpha.md", '---\ntitle: "Alpha"\ntype: specialist\nstatus: alive\nmember-of: ["[[The Shop]]"]\n---\n# Alpha\n')
# Moved in by a session, not a cycle: the roster below has never heard of it.
w("Shop/Beta Maker.md", '---\ntitle: "Beta Maker"\ntype: maker\nstatus: stub\n---\n# Beta Maker\n')
w("The Shop.md", f"# The Shop\n\n## Roster\n\n{START}\n**1 Specialists** (hand-written, stale)\n<!-- ROSTER:END -->\n")

STALE = "E4  stale generated block:  The Shop.md § Roster  (its sources changed; refresh with: node Shop/Maker/build-roster.mjs)"
MEMBER = "W3  generated-block source in The Shop.md § Roster:  Beta Maker.md: type maker but no `member-of [[The Shop]]` link"

try:
    fails = []
    code, found = lint()
    if code != 1 or found != sorted([STALE, MEMBER]):
        fails.append(f"stale roster: exit {code}, got {found}")

    subprocess.run(["node", os.path.join(ROOT, BUILDER)], capture_output=True, check=True)
    code, found = lint()
    if code != 0 or found != [MEMBER]:
        fails.append(f"after the builder ran: exit {code}, got {found}")

    shutil.rmtree(os.path.join(ROOT, "Shop", "Maker"))
    code, found = lint()
    if found:
        fails.append(f"no builder: got {found}")

    if fails:
        print("FAIL\n  " + "\n  ".join(fails))
        sys.exit(1)
    print("PASS  lint-doc-drift E4/W3: a stale roster errors, the member-of warning passes through, "
          "a fresh one is clean, a root without the builder is skipped")
finally:
    shutil.rmtree(ROOT, ignore_errors=True)
