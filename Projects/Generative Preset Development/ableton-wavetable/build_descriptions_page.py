"""
build_descriptions_page.py — renders describe_preset.py's prose for a set of
Wavetable presets into one static page, each card carrying the parameter dump
it replaces behind a fold, so the two can be compared in place.

Run from ableton-wavetable/:  python3 build_descriptions_page.py
Writes descriptions/preset-descriptions.html and descriptions/all-descriptions.txt
"""
import glob
import html
import os

import analyze_preset as v1
import analyze_preset_v2 as v2
import describe_preset as dp

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "descriptions")

FEATURED = [
    "decompressed-samples/Synth Pad__Aqueous Pad.xml",
    "decompressed-samples/Bass__Abdominal Bass.xml",
    "decompressed-samples/Percussive__Bunker Kick.xml",
    "decompressed-samples/Guitar & Plucked__Arpeggiate Me.xml",
    "decompressed-samples/Mallets__A Brief History of Chime.xml",
    "decompressed-samples/Brass__Alphalog Brass.xml",
    "generated/light-through-deep-water/LTDW 1 Caustics.adv",
    "generated/light-through-deep-water/LTDW 2 Shaft.adv",
    "generated/light-through-deep-water/LTDW 3 Refraction.adv",
]

CSS = """
:root{--serif:'Cormorant Garamond','Source Serif 4',Georgia,serif;--sans:'Manrope',system-ui,sans-serif;
--mono:'JetBrains Mono',ui-monospace,Menlo,monospace;--bg:#0a0a0f;--e1:#12121a;--e2:#1a1a28;--border:#4a4a5e;
--fg1:#e8e8f0;--fg2:#c8c8d8;--fg3:#8a8aa0;--accent:#e8b84a;--accent-line:rgba(232,184,74,.5)}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg1);font-family:var(--sans);font-size:15px}
main{max-width:860px;margin:0 auto;padding:40px 24px 64px}
.eyebrow{font-family:var(--mono);font-size:11px;letter-spacing:.14em;text-transform:uppercase;color:var(--fg3)}
h1{font-family:var(--serif);font-weight:400;font-size:40px;line-height:1.15;margin:10px 0 14px}
.intro{font-family:var(--serif);font-size:17px;line-height:1.75;color:var(--fg2);max-width:680px}
.card{background:var(--e1);border:1px solid var(--border);border-radius:2px;padding:22px 24px;margin:22px 0}
.card h2{font-family:var(--serif);font-weight:500;font-size:26px;margin:0 0 2px}
.who{font-family:var(--mono);font-size:11px;color:var(--fg3);margin-bottom:12px}
.verdict{font-family:var(--serif);font-size:20px;line-height:1.5;border-left:2px solid var(--accent-line);padding-left:14px;margin:8px 0 14px}
.para{font-family:var(--serif);font-size:17px;line-height:1.75;color:var(--fg2);margin:6px 0}
.para b{font-family:var(--mono);font-size:11px;letter-spacing:.1em;text-transform:uppercase;color:var(--accent);font-weight:500;margin-right:8px}
.sure{font-size:12px;color:var(--fg3);margin-top:12px;line-height:1.5}
details{margin-top:12px}summary{cursor:pointer;font-family:var(--mono);font-size:11px;color:var(--fg3);letter-spacing:.08em}
pre{background:var(--e2);color:var(--fg3);font-family:var(--mono);font-size:11px;line-height:1.5;padding:12px;overflow-x:auto;white-space:pre-wrap;border-radius:2px}
.dag{color:var(--accent)}footer{margin-top:40px;font-family:var(--mono);font-size:11px;color:var(--fg3)}
"""


def dump(path):
    desc, _ = v1.describe(path, v1.load_slot_kinds())
    return v2.MARKER.sub(lambda m: v2.resolve(m.group(1)), desc)


def esc(s):
    return html.escape(s).replace("†", '<span class="dag">†</span>')


def card(path):
    d, head, paras, foot = dp.describe(path)
    origin = "generated by this project" if path.endswith(".adv") else \
        "Ableton factory · %s" % (d["category"] or "")
    who = origin + (" · %s" % d["author"] if d["author"] else "")
    out = ['<section class="card"><h2>%s</h2><div class="who">%s</div>' % (esc(d["name"]), esc(who)),
           '<div class="verdict">%s</div>' % esc(paras[0])]
    for label, p in zip(("Source", "Filter", "Shape", "Motion", "Playing"), paras[1:]):
        out.append('<p class="para"><b>%s</b>%s</p>' % (label, esc(p)))
    out.append('<div class="sure">%s</div>' % esc(foot))
    out.append('<details><summary>the parameter list this replaces</summary><pre>%s</pre></details></section>'
               % esc(dump(path)))
    return "\n".join(out)


def main():
    os.makedirs(OUT, exist_ok=True)
    cards = [card(os.path.join(HERE, p)) for p in FEATURED]
    page = """<!doctype html><html><head><meta charset="utf-8"><title>Wavetable presets, described</title>
<style>%s</style></head><body><main>
<div class="eyebrow">Study · Generative Preset Development · Ableton Wavetable</div>
<h1>Nine Wavetable presets, described the way a synthesist would</h1>
<p class="intro">Six of Ableton's own factory presets and the three pads made this week from
"light through deep water". Each one starts with a single sentence verdict, then where the sound
comes from, how it is filtered, how it is shaped, what moves it, and what your playing changes.
The old parameter list sits under each card for comparison. A <span class="dag">†</span> marks
a feel-word borrowed from how Ableton's factory presets set that knob; once your ear sitting
lands, those marks disappear on their own.</p>
%s
<footer>describe_preset.py · nothing here has been checked against Live by ear yet</footer>
</main></body></html>""" % (CSS, "\n".join(cards))
    with open(os.path.join(OUT, "preset-descriptions.html"), "w") as f:
        f.write(page)
    files = sorted(glob.glob(os.path.join(HERE, "decompressed-samples", "*.xml"))) + \
        sorted(glob.glob(os.path.join(HERE, "generated", "*", "*.adv")))
    with open(os.path.join(OUT, "all-descriptions.txt"), "w") as f:
        for p in files:
            d, head, paras, foot = dp.describe(p)
            f.write(dp.render_text(head, paras, foot) + "\n")
    print("wrote %d cards, %d text descriptions" % (len(cards), len(files)))


if __name__ == "__main__":
    main()
