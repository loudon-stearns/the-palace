#!/usr/bin/env node
// emit_plugin.js — PDL → a VST3/AU plugin, through VST Template's machinery
// (Generative Audio Devices, 2026-11-04). The native target's patch.h, the
// kit and the voice engine the Mac app plays are dropped unchanged into a
// plugin folder made by VST Template's new-plugin.py, with an Algorithm.h
// that hands MIDI to the engine and every knob to the host as a parameter.
// So the app and the plugin play one engine, and the plugin is built,
// verified, validated and installed by the same machinery as Simple Synth.
//
// The "sketch" the template checks against is reference/ref.cpp: the same
// engine driven outside the plugin, with the same knob values and notes.
// Its exact gate proves Algorithm.h drives the patch as the app does; the
// plugin gate proves the real processBlock, MIDI and smoothing keep it.
//
// Usage:  node emit_plugin.js <file.pdl> --into <plugin dir> --name "Title" --code Abcd
// A folder that doesn't exist is made with new-plugin.py first; one that
// does is regenerated in place (its plugin.json name and code are kept).

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const { emitNative, loadRenderer } = require("./emit_native.js");
const HERE = __dirname;
const NATIVE = JSON.parse(fs.readFileSync(path.join(HERE, "native_registry.json"), "utf8"));
const NEW_PLUGIN = path.join(HERE, "..", "..", "VST Template", "new-plugin.py");

const ident = (s) => s.replace(/[^A-Za-z0-9_]/g, "_");
const num = (x) => { let s = String(+(+x).toFixed(6)); if (!/[.e]/.test(s)) s += ".0"; return s; };

function knobTable(pdlText, R) {
  const g = R.resolvePatch(pdlText);
  const rows = [];
  for (const [id, t] of Object.entries(g.instanceTypes)) {
    const m = NATIVE.modules[t]; if (!m || m.role) continue;
    for (const pn of m.params) {
      const val = (g.knobs[id] || {})[pn]; if (val == null) continue;
      const spec = (R.VCV[t].params || []).find(p => p.name === pn); if (!spec) continue;
      const [lo, hi] = spec.range, toggle = spec.unit === "toggle";
      rows.push({ id: `${ident(id)}_${pn}`.toLowerCase(), name: `${id} ${pn.replace(/_/g, " ")}`, inst: ident(id), struct: m.struct, pn,
        unit: spec.unit === "semitones" ? "st" : "", lo, hi, def: Math.min(hi, Math.max(lo, val)), toggle,
        group: `${id} · ${t}`, hero: t === "VCF" && (pn === "FREQ" || pn === "RES") });
    }
  }
  // only the first filter's two knobs are heroes
  const firstVcf = rows.find(r => r.hero)?.inst; rows.forEach(r => { if (r.inst !== firstVcf) r.hero = false; });
  return rows;
}

function main() {
  const args = process.argv.slice(2);
  const opt = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
  const pdlFile = args[0], into = opt("--into"), name = opt("--name"), code = opt("--code");
  if (!pdlFile || !into || !name) { console.error('usage: node emit_plugin.js <file.pdl> --into <dir> --name "Title" [--code Abcd]'); process.exit(2); }
  const dir = path.resolve(into);
  if (!fs.existsSync(dir)) {
    if (!code) { console.error("a new plugin needs --code (four letters, one capital first)"); process.exit(2); }
    execFileSync("python3", [NEW_PLUGIN, name, code, "--into", dir], { stdio: "inherit" });
  }
  const pdl = fs.readFileSync(pdlFile, "utf8");
  const r = emitNative(pdl, { name, source: path.basename(pdlFile) });
  if (r.problems) { r.problems.forEach(p => console.error("cannot build: " + p)); process.exit(1); }
  r.notes.forEach(n => console.error("note: " + n));
  const R = loadRenderer();
  const rows = knobTable(pdl, R);
  const stereo = /\bright = \(/.test(r.header);
  const src = path.join(dir, "src"), ref = path.join(dir, "reference");

  fs.writeFileSync(path.join(src, "patch.h"), r.header);
  for (const f of ["gad_kit.h", "host_common.h"])
    fs.writeFileSync(path.join(src, f), `// Copied from Generative Audio Devices/native/${f} by emit_plugin.js. Edit it there.\n` + fs.readFileSync(path.join(HERE, f), "utf8"));
  fs.copyFileSync(pdlFile, path.join(ref, path.basename(pdlFile)));

  // knobs.h — the one place a knob value reaches the patch, shared by the plugin and ref.cpp.
  const K = [];
  K.push(`// knobs.h — generated by emit_plugin.js from ${path.basename(pdlFile)}. Do not edit; edit the PDL.`);
  K.push(`// v[i] is parameter i in natural units, in the order of kParams; the last is level in dB.`);
  K.push(`#pragma once`, `#define PATCH_H "patch.h"`, `#include "host_common.h"`, `#include <cmath>`, ``, `namespace knobs {`);
  K.push(`constexpr int N = ${rows.length + 1};`, `constexpr int LEVEL = ${rows.length};`, `constexpr int OUTPUTS = ${stereo ? 2 : 1};`);
  K.push(`inline void apply(Engine& e, const double* v) {`, `  for (auto& x : e.v) {`);
  rows.forEach((k, i) => K.push(`    x.${k.inst}.p[gad::${k.struct}::${k.pn}] = (float) v[${i}];`));
  K.push(`  }`, `}`);
  K.push(`// one sample: the knobs, the engine, then the level (the same expression in both places)`);
  K.push(`inline void step(Engine& e, const double* v, double sr, float* out) {`);
  K.push(`  apply(e, v);`, `  float l, r; e.tick((float) (1.0 / sr), l, r);`, `  const double gain = std::pow(10.0, v[LEVEL] / 20.0);`);
  K.push(`  out[0] = (float) (gain * l);`, ...(stereo ? [`  out[1] = (float) (gain * r);`] : []), `}`, `} // namespace knobs`, ``);
  fs.writeFileSync(path.join(src, "knobs.h"), K.join("\n"));

  // Algorithm.h — VST Template's contract, filled from the patch.
  const A = [];
  A.push(`// Algorithm.h — ${name}, generated by Generative Audio Devices' emit_plugin.js`);
  A.push(`// from ${path.basename(pdlFile)}. Do not edit; edit the PDL and regenerate.`);
  A.push(`// The patch (patch.h), the module kit (gad_kit.h) and the voice engine`);
  A.push(`// (host_common.h) are the native target's, the same files the Mac app plays.`);
  A.push(`#pragma once`, ``, `#include "ParamSpec.h"`, `#include "knobs.h"`, ``, `namespace algo`, `{`);
  A.push(`    using tpl::ParamSpec;`, `    using tpl::Taper;`, ``);
  A.push(`    inline constexpr int kNumParams = knobs::N;`);
  A.push(`    inline constexpr ParamSpec kParams[kNumParams] = {`);
  A.push(`        //  id   name   unit   min   max   default   taper   smooth   choices   auto   group   hero`);
  for (const k of rows)
    A.push(`        { ${JSON.stringify(k.id)}, ${JSON.stringify(k.name)}, ${JSON.stringify(k.unit)}, ${num(k.lo)}, ${num(k.hi)}, ${num(k.def)}, ${k.toggle ? "Taper::Toggle, 0.0" : "Taper::Linear, 20.0"}, "", true, ${JSON.stringify(k.group)}${k.hero ? ", true" : ""} },`);
  A.push(`        { "level", "Level", "dB", -60.0, 6.0, 0.0, Taper::Linear, 20.0, "", true, "Output" },`, `    };`, ``);
  A.push(`    inline constexpr int kInputs  = 0;`, `    inline constexpr int kOutputs = knobs::OUTPUTS;`);
  A.push(`    inline constexpr const char* kProbes[] = { "held" };`, `    inline constexpr int kNumProbes = 1;`, ``);
  A.push(`    struct Algorithm`, `    {`, `        double sr = 44100.0;`, `        Engine e;`, `        double probes[kNumProbes] {};`, ``);
  A.push(`        void prepare (double sampleRate) { sr = sampleRate; }`);
  A.push(`        void reset (const double*) { e = Engine(); }`);
  A.push(`        void noteOn (int note, double) { e.on (note); }   // the engine plays every note at velocity 127, as Rack's QWERTY keyboard does`);
  A.push(`        void noteOff (int note) { e.off (note); }`);
  A.push(`        void step (const double* v, const float*, float* out) { knobs::step (e, v, sr, out); probes[0] = e.nheld; }`);
  A.push(`    };`, `}`, ``);
  fs.writeFileSync(path.join(src, "Algorithm.h"), A.join("\n"));

  // reference/ref.cpp — the same engine outside the plugin; sketch.py drives it.
  fs.writeFileSync(path.join(ref, "ref.cpp"), `// ref.cpp — the reference for verify.py: the native target's engine driven
// outside the plugin. stdin: int32 steps, nparams, nnotes; float64 v[nparams][steps];
// int32 notes[nnotes][4] (sample, on, note, velocity). stdout: float64 out[outputs][steps],
// then float64 held[steps]. Generated by emit_plugin.js.
#include "knobs.h"
#include <cstdio>
#include <cstdint>
#include <vector>
int main() {
  int32_t h[3]; if (fread(h, 4, 3, stdin) != 3) return 1;
  const int steps = h[0], np = h[1], nn = h[2];
  if (np != knobs::N) { fprintf(stderr, "ref: %d params given, the patch has %d\\n", np, knobs::N); return 1; }
  std::vector<double> v((size_t) np * steps); fread(v.data(), 8, v.size(), stdin);
  std::vector<int32_t> ev((size_t) nn * 4); fread(ev.data(), 4, ev.size(), stdin);
  std::vector<double> out((size_t) knobs::OUTPUTS * steps), held(steps), col(np);
  Engine* e = new Engine(); int k = 0;
  for (int i = 0; i < steps; i++) {
    for (; k < nn && ev[k * 4] <= i; k++) { if (ev[k * 4 + 1]) e->on(ev[k * 4 + 2]); else e->off(ev[k * 4 + 2]); }
    for (int j = 0; j < np; j++) col[j] = v[(size_t) j * steps + i];
    float o[2] = {0, 0}; knobs::step(*e, col.data(), 44100.0, o);
    for (int c = 0; c < knobs::OUTPUTS; c++) out[(size_t) c * steps + i] = o[c];
    held[i] = e->nheld;
  }
  fwrite(out.data(), 8, out.size(), stdout); fwrite(held.data(), 8, held.size(), stdout);
}
`);
  fs.writeFileSync(path.join(ref, "sketch.py"), `"""sketch.py — the reference for ${name}, generated by Generative Audio Devices'
emit_plugin.js. Not a numpy port: the patch's reference is the native target's
own engine, the one the Mac app plays, driven outside the plugin by ref.cpp
(built here on first use). The exact gate then proves Algorithm.h drives the
patch the way the app does; the plugin gate proves processBlock, MIDI and
smoothing keep it.
"""
import subprocess
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "src"
EXE = HERE.parent / "out" / "ref"


def _build():
    deps = [HERE / "ref.cpp"] + sorted(SRC.glob("*.h"))
    if EXE.exists() and EXE.stat().st_mtime > max(d.stat().st_mtime for d in deps):
        return
    EXE.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["clang++", "-std=c++17", "-O2", f"-I{SRC}", str(HERE / "ref.cpp"), "-o", str(EXE)], check=True)


def render(v, sr, inputs=None, notes=()):
    assert sr == 44100, "ref.cpp runs at 44.1 kHz, as the paths do"
    _build()
    ids = list(v)   # verify.py gives every parameter, in kParams order
    steps = len(v[ids[0]])
    rows = np.ascontiguousarray(np.stack([np.asarray(v[i], dtype=np.float64) for i in ids]))
    ev = np.array([(s, int(on), n, vel) for s, on, n, vel in notes], dtype=np.int32).reshape(-1, 4)
    stdin = np.array([steps, len(ids), len(ev)], dtype=np.int32).tobytes() + rows.tobytes() + ev.tobytes()
    raw = subprocess.run([str(EXE)], input=stdin, capture_output=True, check=True).stdout
    a = np.frombuffer(raw, "<f8")
    outs = len(a) // steps - 1
    return dict(out=a[: outs * steps].reshape(outs, steps), probes={"held": a[outs * steps:]})
`);

  const vcf = rows.find(k => k.hero && k.pn === "FREQ");
  const poly = r.voices > 1;
  const P = [];
  P.push(`"""paths.py — what ${name} must pass. Generated by emit_plugin.js.`);
  P.push(`Nothing in a Fundamental patch is chaotic, so every path must match the`);
  P.push(`reference sample for sample."""`, ``, `SR = 44100`, ``, `PATHS = [`);
  P.push(`    # the figure host_render.cpp plays: four notes, the last held`);
  P.push(`    dict(name="figure", secs=3.0,`, `         notes=[(0.0, 0.2, 36, 100), (0.25, 0.2, 36, 100), (0.5, 0.2, 43, 100), (0.75, 1.5, 48, 100)],`, `         gate=dict(exact_until=None)),`);
  P.push(`    # a note held under another, then let go: last-note priority falls back to the held one`);
  P.push(`    dict(name="legato", secs=2.5,`, `         notes=[(0.0, 1.6, 36, 100), (0.4, 0.6, 43, 100), (1.8, 0.4, 41, 100)],`, `         gate=dict(exact_until=None)),`);
  if (poly) P.push(`    # a chord, then another`, `    dict(name="chords", secs=3.0,`, `         notes=[(0.0, 1.2, n, 100) for n in (48, 52, 55, 59)] + [(1.4, 1.2, n, 100) for n in (50, 53, 57, 60)],`, `         gate=dict(exact_until=None)),`);
  if (vcf) P.push(`    # the cutoff swept while a note holds. The plugin smooths the knob over 20 ms,`, `    # so its loudness is allowed 1.5 dB where the reference jumps`, `    dict(name="cutoff-sweep", secs=3.0,`, `         values=dict(${vcf.id}=lambda t: 0.1 + 0.8 * t / 3.0),`, `         notes=[(0.0, 2.8, 36, 100)],`, `         gate=dict(exact_until=None, plugin_rms_db=1.5)),`);
  P.push(`]`, ``);
  fs.writeFileSync(path.join(ref, "paths.py"), P.join("\n"));

  const pj = JSON.parse(fs.readFileSync(path.join(dir, "plugin.json"), "utf8"));
  pj.hostcheck = [...(vcf ? [`${vcf.id}=0.9`] : []), "level=-12"];
  pj.ui = { width: 1180, height: 680, min: [1120, 660], max: [1800, 1100], direction: "bench" };
  fs.writeFileSync(path.join(dir, "plugin.json"), JSON.stringify(pj, null, 2) + "\n");
  console.log(`wrote ${path.relative(process.cwd(), dir)}: ${rows.length + 1} parameters, ${r.voices} voice${r.voices > 1 ? "s" : ""}, ${stereo ? "stereo" : "mono"}`);
}

main();
