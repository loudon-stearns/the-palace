"""make_engine.py — a measuring copy of the plugin's engine with room for 1024 neurons.

The shipped engine (../../src/Algorithm.h) holds 32-256. This copies it, widens the
crowd to 1024 and the size list to 32..1024, and extends the random tables: the first
256 entries are the plugin's own (so crowds up to 256 are the plugin's crowds, exactly),
the rest come from a second seed. Nothing here touches the plugin.
    python3 make_engine.py   # writes Algorithm1024.h and Constants.h beside it
"""
import re, numpy as np, pathlib
here = pathlib.Path(__file__).parent
src = (here / "../../src").resolve()
c = (src / "Constants.h").read_text()
def table(name):
    body = re.search(name + r"\[256\] = \{ (.*?) \};", c).group(1)
    return [float(x) for x in body.split(",")]
ext = np.random.default_rng(20261108)
ur = table("u_rate") + ext.random(768).tolist()
up = table("u_phase") + ext.random(768).tolist()
fmt = lambda v: ", ".join(repr(x) for x in v)
(here / "Constants.h").write_text(
    "// generated by make_engine.py; first 256 entries are the plugin's own\n#pragma once\n"
    "namespace algo::constants\n{\n"
    f"    inline constexpr double u_rate[1024] = {{ {fmt(ur)} }};\n"
    f"    inline constexpr double u_phase[1024] = {{ {fmt(up)} }};\n}}\n")
a = (src / "Algorithm.h").read_text()
a = a.replace("inline constexpr int kMax = 256;", "inline constexpr int kMax = 1024;")
a = a.replace("inline constexpr int kSizes[4] = { 32, 64, 128, 256 };",
              "inline constexpr int kSizes[6] = { 32, 64, 128, 256, 512, 1024 };")
assert "kMax = 1024" in a and "kSizes[6]" in a
(here / "Algorithm1024.h").write_text("// generated by make_engine.py from ../../src/Algorithm.h — don't edit\n" + a)
print("ok")
