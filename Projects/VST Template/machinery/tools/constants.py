#!/usr/bin/env python3
"""constants.py — shared machinery: write the sketch's random constants into
src/Constants.h, so the plugin starts exactly where the sketch does.

  python3 machinery/tools/constants.py <plugin dir>

Does nothing when reference/sketch.py has no constants(). plugin.sh build runs
it before every build; the header is committed, so the plugin also builds
without Python.
"""
import importlib.util
import sys
from pathlib import Path

import numpy as np


def main():
    root = Path(sys.argv[1]).resolve()
    spec = importlib.util.spec_from_file_location("sketch", root / "reference" / "sketch.py")
    sketch = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sketch)
    if not hasattr(sketch, "constants"):
        return
    lines = ["// Constants.h — generated by tools/constants.py from reference/sketch.py. Don't edit:",
             "// change the sketch and rebuild.",
             "#pragma once", "", "namespace algo::constants", "{"]
    for name, values in sketch.constants().items():
        a = np.asarray(values, dtype=np.float64).ravel()
        body = ", ".join(f"{x:.17g}" for x in a)
        lines.append(f"    inline constexpr double {name}[{len(a)}] = {{ {body} }};")
    lines += ["}", ""]
    text = "\n".join(lines)
    out = root / "src" / "Constants.h"
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
        print(f"wrote {out.relative_to(root)}")


if __name__ == "__main__":
    main()
