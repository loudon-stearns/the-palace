# Data and geometry for mobius-loop-odd-half-series.tex: a loop that flips its sign each trip.
#   mlohs-comb.dat   |H(f)| for y = z^-T (x - a y), T = one trip of a 240 Hz loop (200 samples at 48 kHz)
#   mlohs-peaks.dat  the computed peak frequencies
#   mobius-strip.tex a Moebius band (one half twist), painter-sorted, with a path at fixed offset that
#                    needs two laps (u from 0 to 4 pi) to close: lap one ends on the other side
# Run from this folder: python3 mobius-loop-odd-half-series.py
import math
import numpy as np

# ---------- the sound ----------
fs, D, a = 48000, 200, 0.8          # 48000 / 200 = 240 Hz: a plain loop of this length rings at 240, 480, 720
f = np.linspace(0, 1000, 200001)
z = np.exp(-2j * np.pi * f * D / fs)
mag = 1 / np.abs(1 + a * z)          # feedback gain -a
with open('mlohs-comb.dat', 'w') as fo:
    fo.write('f mag\n')
    for x, y in zip(f[::100], mag[::100]):
        fo.write(f'{x:.2f} {y:.4f}\n')
i = np.where((mag[1:-1] > mag[:-2]) & (mag[1:-1] >= mag[2:]))[0] + 1
peaks = [round(float(v), 2) for v in f[i]]
with open('mlohs-peaks.dat', 'w') as fo:
    fo.write('f mag\n')
    for k in i:
        fo.write(f'{f[k]:.2f} {mag[k]:.4f}\n')
print('loop frequency', fs / D, 'Hz; peaks with -a:', peaks)
print('peak height', round(float(mag.max()), 4), '= 1/(1-a); dips', round(float(mag.min()), 4), '= 1/(1+a) at',
      [round(float(v), 2) for v in f[np.where((mag[1:-1] < mag[:-2]) & (mag[1:-1] <= mag[2:]))[0] + 1]])

# ---------- the loop: a Moebius band ----------
R, W = 1.0, 0.42                     # centre radius, half-width
elev, azim = math.radians(58), math.radians(-90)   # look down at an angle; put u = 0 at the front

def P(u, v):
    c = R + v * math.cos(u / 2)
    x, y, zz = c * math.cos(u + azim), c * math.sin(u + azim), v * math.sin(u / 2)
    X = x
    Y = y * math.cos(elev) + zz * math.sin(elev)
    depth = -y * math.sin(elev) + zz * math.cos(elev)    # larger is nearer the viewer
    return X, Y, depth

def normal(u, v):
    e = 1e-4
    p0 = np.array(P(u, v)); pu = (np.array(P(u + e, v)) - p0) / e; pv = (np.array(P(u, v + e)) - p0) / e
    n = np.cross(pu, pv); return n / np.linalg.norm(n)

N = 180
du = 2 * math.pi / N
VP = 0.5 * W                         # the traced path's offset from the centre line
items = []                           # (depth, order, tikz)
for k in range(N):
    u0, u1 = k * du, (k + 1) * du
    q = [P(u0, -W), P(u1, -W), P(u1, W), P(u0, W)]
    d = sum(p[2] for p in q) / 4
    nz = abs(normal((u0 + u1) / 2, 0)[2])                 # how squarely this piece faces the eye
    shade = int(round(20 + 45 * (1 - nz)))                # slab percentage over paper: edge-on reads darker
    poly = ' -- '.join(f'({p[0]:.3f},{p[1]:.3f})' for p in q)
    items.append((d, 0, f'\\filldraw[fill=slab!{shade}!paper, draw=slab!{shade}!paper, line width=0.2pt] {poly} -- cycle;'))
    for v in (-W, W):                                      # the band's one edge, a piece at a time
        a0, a1 = P(u0, v), P(u1, v)
        items.append((d, 1, f'\\draw[ink2, line width=0.6pt, line cap=round] ({a0[0]:.3f},{a0[1]:.3f}) -- ({a1[0]:.3f},{a1[1]:.3f});'))
    if k % 15 == 0:                                        # a few faint rulings across the band
        b0, b1 = P(u0, -W), P(u0, W)
        items.append((d, 1, f'\\draw[ink3!50, line width=0.25pt] ({b0[0]:.3f},{b0[1]:.3f}) -- ({b1[0]:.3f},{b1[1]:.3f});'))
    for lap in (0, 1):                                     # the path: lap 0 at +VP, lap 1 lands at -VP on this piece
        uu0, uu1 = u0 + lap * 2 * math.pi, u1 + lap * 2 * math.pi
        c0, c1 = P(uu0, VP), P(uu1, VP)
        if lap == 1 and k % 7 >= 4:                         # trip two drawn dashed: 4 pieces on, 3 off
            continue
        style = 'loop'
        items.append((d, 2, f'\\draw[{style}, line cap=round] ({c0[0]:.3f},{c0[1]:.3f}) -- ({c1[0]:.3f},{c1[1]:.3f});'))
items.sort(key=lambda t: (t[0], t[1]))
with open('mobius-strip.tex', 'w') as fo:
    fo.write('% a Moebius band with a path that needs two laps to close; generated by mobius-loop-odd-half-series.py\n')
    for _, _, s in items:
        fo.write(s + '\n')
    # start (and home, after two laps) and where one lap lands
    s0, s1 = P(0, VP), P(2 * math.pi, VP)
    fo.write(f'\\coordinate (mstart) at ({s0[0]:.3f},{s0[1]:.3f});\n\\coordinate (mlap) at ({s1[0]:.3f},{s1[1]:.3f});\n')
    for name, u in (('marrA', 0.30 * 2 * math.pi), ('marrB', 1.70 * 2 * math.pi)):
        p, q = P(u, VP), P(u + 0.05, VP)
        fo.write(f'\\coordinate ({name}) at ({p[0]:.3f},{p[1]:.3f});\\coordinate ({name}2) at ({q[0]:.3f},{q[1]:.3f});\n')
    print('start depth', round(s0[2], 3), 'lap-one point depth', round(s1[2], 3),
          'same place?', np.allclose(P(0, VP)[:2], P(4 * math.pi, VP)[:2]),
          'lap one lands at offset -VP:', np.allclose(P(2 * math.pi, VP)[:2], P(0, -VP)[:2]))
