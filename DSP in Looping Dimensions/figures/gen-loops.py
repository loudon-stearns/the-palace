# Geometry for where-the-loops-meet.tex, written as TikZ snippets (text-first, regenerable).
#   torus-mesh.tex   faint meridians and parallels of a torus seen from above at an angle
#   torus-path.tex   a scan at f2/f1 = golden ratio winding over it, front solid and back dashed
#   stretch-rings.tex  panel 3: each partial's own loop, n/f_n = T / sqrt(1 + B n^2)
# Run from this folder: python3 gen-loops.py
import math
phi = (1 + 5 ** 0.5) / 2
R, r, elev = 1.75, 0.68, math.radians(52)   # torus radii, viewing elevation

def proj(u, v):
    x = (R + r * math.cos(v)) * math.cos(u)
    y = (R + r * math.cos(v)) * math.sin(u)
    z = r * math.sin(v)
    X = x
    Y = y * math.cos(elev) + z * math.sin(elev)
    depth = -y * math.sin(elev) + z * math.cos(elev)   # larger is nearer the viewer
    return X, Y, depth

def visible(u, v):
    # a point faces the viewer when its surface normal points toward the eye
    nx, ny, nz = math.cos(v) * math.cos(u), math.cos(v) * math.sin(u), math.sin(v)
    return (-ny * math.sin(elev) + nz * math.cos(elev)) > 0

def segments(points):
    """split a polyline into runs of equal visibility"""
    runs, cur, vis = [], [], None
    for X, Y, v in points:
        if vis is None or v == vis:
            cur.append((X, Y))
        else:
            cur.append((X, Y)); runs.append((vis, cur)); cur = [(X, Y)]
        vis = v
    if cur: runs.append((vis, cur))
    return runs

def draw(f, runs, front_style, back_style):
    for vis, pts in runs:
        if len(pts) < 2: continue
        style = front_style if vis else back_style
        if style is None: continue
        f.write(f'\\draw[{style}] ' + ' -- '.join(f'({x:.3f},{y:.3f})' for x, y in pts) + ';\n')

with open('torus-mesh.tex', 'w') as f:
    f.write('% torus mesh, generated by gen-loops.py\n')
    for k in range(24):                       # meridians: the small circle, phi_2
        u = 2 * math.pi * k / 24
        pts = [(*proj(u, 2 * math.pi * i / 80)[:2], visible(u, 2 * math.pi * i / 80)) for i in range(81)]
        draw(f, segments(pts), 'mesh', None)
    for k in range(8):                        # parallels: the big circle, phi_1
        v = 2 * math.pi * k / 8
        pts = [(*proj(2 * math.pi * i / 160, v)[:2], visible(2 * math.pi * i / 160, v)) for i in range(161)]
        draw(f, segments(pts), 'mesh', None)

with open('torus-path.tex', 'w') as f:
    f.write('% a scan winding at f2/f1 = golden ratio, generated by gen-loops.py\n')
    N, turns = 2400, 3.0
    pts = []
    for i in range(N + 1):
        u = 2 * math.pi * turns * i / N
        v = phi * u
        X, Y, _ = proj(u, v)
        pts.append((X, Y, visible(u, v)))
    draw(f, segments(pts), 'scan', 'scanback')

with open('stretch-rings.tex', 'w') as f:
    f.write('% panel 3: partial n goes round a loop of length T / sqrt(1 + B n^2), B exaggerated; generated by gen-loops.py\n')
    B, R0 = 0.06, 1.75
    for n in range(1, 9):
        rad = R0 / math.sqrt(1 + B * n * n)
        f.write(f'\\draw[ring] (0,0) circle ({rad:.3f});\n')
        if n in (1, 8):
            a = math.radians(30 if n == 1 else -30)
            f.write(f'\\draw[ink3, line width=0.3pt] ({rad * math.cos(a):.3f},{rad * math.sin(a):.3f}) -- ({2.1 * math.cos(a):.3f},{2.1 * math.sin(a):.3f}) node[lab, anchor=west] {{n = {n}}};\n')
print('wrote torus-mesh.tex, torus-path.tex, stretch-rings.tex')
