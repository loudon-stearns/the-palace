# Data and geometry for ratio-sweep-gates.tex: sweep r = f2/f1 from 1.30 to 1.75 and draw every lattice
# line m + n*r with |m| + |n| <= 5 that lies in 0 < f < 6 (frequency in multiples of f1).
#   rsg-lines-w{1..5}.dat   line segments by order |m| + |n| (blank line between segments)
#   rsg-folds.dat           points on a gate where two or more drawn lines meet
#   rsg-torus-mesh.tex, rsg-knot-32.tex, rsg-knot-phi.tex, rsg-knot-53.tex   the mini tori
# Run from this folder: python3 ratio-sweep-gates.py
import math
from fractions import Fraction
from collections import defaultdict
phi = (1 + 5 ** 0.5) / 2
R0, R1, FMAX = 1.30, 1.75, 6.0

# ---- lattice lines, clipped to 0 < f < FMAX ----
by_order = defaultdict(list)
for m in range(-5, 6):
    for n in range(-5, 6):
        w = abs(m) + abs(n)
        if w == 0 or w > 5: continue
        f = lambda r: m + n * r
        if n == 0:
            if not 0 < m < FMAX: continue
            a, b = R0, R1
        else:
            lo, hi = sorted(((0 - m) / n, (FMAX - m) / n))   # where 0 < m + n r < FMAX
            a, b = max(R0, lo), min(R1, hi)
            if b - a < 1e-9: continue
        by_order[w].append((m, n, a, f(a), b, f(b)))
for w in range(1, 6):
    with open(f'rsg-lines-w{w}.dat', 'w') as fh:
        fh.write('r f\n')
        for m, n, a, fa, b, fb in by_order[w]:
            fh.write(f'{a:.5f} {fa:.5f}\n{b:.5f} {fb:.5f}\n\n')

# ---- folds: exact coincidences on the rational gates (and a check that phi has none) ----
gates = {'4/3': Fraction(4, 3), '3/2': Fraction(3, 2), '8/5': Fraction(8, 5), '5/3': Fraction(5, 3)}
lines = [(m, n) for w in by_order for m, n, *_ in by_order[w]]
with open('rsg-folds.dat', 'w') as fh:
    fh.write('r f count\n')
    for name, g in gates.items():
        hits = defaultdict(int)
        for m, n in lines:
            v = m + n * g
            if 0 < v < FMAX: hits[v] += 1
        folds = {v: c for v, c in hits.items() if c >= 2}
        print(f'gate {name}: {len(hits)} distinct points, {len(folds)} folds, max lines at one point {max(folds.values(), default=1)}')
        for v, c in sorted(folds.items()):
            fh.write(f'{float(g):.5f} {float(v):.5f} {c}\n')
vals = sorted(m + n * phi for m, n in lines if 0 < m + n * phi < FMAX)
print(f'gate phi: closest two lines {min(b - a for a, b in zip(vals, vals[1:])):.4f} f1 apart')
print('lines by order:', {w: len(v) for w, v in sorted(by_order.items())})

# ---- mini tori: the projection code of gen-loops.py, copied so this script writes nothing else ----
R, r, elev = 1.75, 0.68, math.radians(52)
def proj(u, v):
    x = (R + r * math.cos(v)) * math.cos(u); y = (R + r * math.cos(v)) * math.sin(u); z = r * math.sin(v)
    return x, y * math.cos(elev) + z * math.sin(elev)
def visible(u, v):
    nx, ny, nz = math.cos(v) * math.cos(u), math.cos(v) * math.sin(u), math.sin(v)
    return (-ny * math.sin(elev) + nz * math.cos(elev)) > 0
def segments(points):
    runs, cur, vis = [], [], None
    for X, Y, v in points:
        if vis is None or v == vis: cur.append((X, Y))
        else: cur.append((X, Y)); runs.append((vis, cur)); cur = [(X, Y)]
        vis = v
    if cur: runs.append((vis, cur))
    return runs
def draw(f, runs, front, back):
    for vis, pts in runs:
        style = front if vis else back
        if len(pts) < 2 or style is None: continue
        f.write(f'\\draw[{style}] ' + ' -- '.join(f'({x:.3f},{y:.3f})' for x, y in pts) + ';\n')

with open('rsg-torus-mesh.tex', 'w') as f:
    f.write('% mini torus mesh, generated by ratio-sweep-gates.py\n')
    for k in range(12):
        u = 2 * math.pi * k / 12
        draw(f, segments([(*proj(u, 2 * math.pi * i / 60), visible(u, 2 * math.pi * i / 60)) for i in range(61)]), 'mesh', None)
    for k in range(4):
        v = 2 * math.pi * k / 4
        draw(f, segments([(*proj(2 * math.pi * i / 120, v), visible(2 * math.pi * i / 120, v)) for i in range(121)]), 'mesh', None)

for name, ratio, turns in (('32', 1.5, 2), ('53', 5 / 3, 3), ('phi', phi, 6)):
    N = 900 * turns
    pts = []
    for i in range(N + 1):
        u = 2 * math.pi * turns * i / N; v = ratio * u
        pts.append((*proj(u, v), visible(u, v)))
    end = proj(2 * math.pi * turns, ratio * 2 * math.pi * turns); start = proj(0, 0)
    gap = math.dist(end, start)
    print(f'knot {name}: {turns} turns of phi1, {ratio * turns:.3f} of phi2, end-to-start gap {gap:.4f}')
    with open(f'rsg-knot-{name}.tex', 'w') as f:
        f.write(f'% scan at f2/f1 = {ratio:.5f} over {turns} turns, generated by ratio-sweep-gates.py\n')
        draw(f, segments(pts), 'knot', 'knotback')
