# Geometry and data for torus-knot-closed-and-open.tex: two phasors read through one table,
# once at 2 : 3 (the path closes: the (2, 3) torus knot, a trefoil) and once at the golden ratio (it never closes).
#   tkco-mesh.tex    faint meridians and parallels of the torus (same projection as gen-loops.py)
#   tkco-knot.tex    u = 2t, v = 3t, t in [0, 2 pi]: heavy in front, dashed behind
#   tkco-fill.tex    u = t, v = phi t, several turns: the path that fills the surface
#   tkco-closed.dat  lines at m f1 + n f2, f2 = 1.5 f1  (every one on the series of f0 = f1 / 2)
#   tkco-open.dat    lines at m f1 + n f2, f2 = phi f1
# Run from this folder: python3 torus-knot-closed-and-open.py
import math
phi = (1 + 5 ** 0.5) / 2
R, r, elev = 1.75, 0.68, math.radians(32)   # torus radii (as gen-loops.py); tilted 32 deg from straight down, not its 52, so the knot's 3-fold symmetry reads

def proj(u, v):
    x = (R + r * math.cos(v)) * math.cos(u)
    y = (R + r * math.cos(v)) * math.sin(u)
    z = r * math.sin(v)
    return x, y * math.cos(elev) + z * math.sin(elev)

def visible(u, v):
    ny, nz = math.cos(v) * math.sin(u), math.sin(v)
    return (-ny * math.sin(elev) + nz * math.cos(elev)) > 0

def segments(points):
    runs, cur, vis = [], [], None
    for X, Y, v in points:
        if vis is None or v == vis:
            cur.append((X, Y))
        else:
            cur.append((X, Y)); runs.append((vis, cur)); cur = [(X, Y)]
        vis = v
    if cur: runs.append((vis, cur))
    return runs

def draw(f, runs, front, back):
    for vis, pts in runs:
        style = front if vis else back
        if len(pts) < 2 or style is None: continue
        f.write(f'\\draw[{style}] ' + ' -- '.join(f'({x:.3f},{y:.3f})' for x, y in pts) + ';\n')

def curve(fu, fv, t_end, N):
    pts = []
    for i in range(N + 1):
        t = t_end * i / N
        u, v = fu * t, fv * t
        pts.append((*proj(u, v), visible(u, v)))
    return pts

with open('tkco-mesh.tex', 'w') as f:
    f.write('% torus mesh, generated by torus-knot-closed-and-open.py\n')
    for k in range(24):
        u = 2 * math.pi * k / 24
        draw(f, segments([(*proj(u, 2 * math.pi * i / 80), visible(u, 2 * math.pi * i / 80)) for i in range(81)]), 'mesh', None)
    for k in range(8):
        v = 2 * math.pi * k / 8
        draw(f, segments([(*proj(2 * math.pi * i / 160, v), visible(2 * math.pi * i / 160, v)) for i in range(161)]), 'mesh', None)

# the knot: twice round the big circle (phi_1), three times round the tube (phi_2), then home
knot = curve(2, 3, 2 * math.pi, 1800)
gap = math.dist(knot[0][:2], knot[-1][:2])
assert gap < 1e-9, gap
with open('tkco-knot.tex', 'w') as f:
    f.write('% the (2, 3) torus knot, generated by torus-knot-closed-and-open.py; closes after t = 2 pi\n')
    draw(f, segments(knot), 'knot', 'knotback')

TURNS = 12
fill = curve(1, phi, 2 * math.pi * TURNS, 6000)
gap_fill = math.dist(fill[0][:2], fill[-1][:2])
with open('tkco-fill.tex', 'w') as f:
    f.write(f'% u = t, v = phi t for {TURNS} turns of u, generated by torus-knot-closed-and-open.py\n')
    draw(f, segments(fill), 'fill', 'fillback')

def lattice(ratio, name, order=5, top=5.6):
    lines = {}
    for m in range(-order, order + 1):
        for n in range(-order, order + 1):
            fr = m + n * ratio
            if 0.05 < fr < top and abs(m) + abs(n) <= order:
                key = round(fr, 6)
                a = 0.62 ** (abs(m) + abs(n) - 1)          # the weights of gen-where-the-loops-meet.py
                lines[key] = max(lines.get(key, 0), a)     # coincident lines: keep the loudest
    with open(name, 'w') as f:
        f.write('freq amp\n')
        for fr in sorted(lines):
            f.write(f'{fr:.4f} {lines[fr]:.4f}\n')
    return sorted(lines)

closed = lattice(1.5, 'tkco-closed.dat')
opened = lattice(phi, 'tkco-open.dat')
off = [fr for fr in closed if abs(fr * 2 - round(fr * 2)) > 1e-9]
assert not off, off   # every closed line sits on the series of f0 = f1 / 2
print(f'knot closes: gap {gap:.2e}; fill after {TURNS} turns still {gap_fill:.3f} from its start')
print(f'closed: {len(closed)} distinct lines, all on multiples of f1/2: {closed}')
print(f'open: {len(opened)} distinct lines; on the f0 grid: {[x for x in opened if abs(x*2-round(x*2))<1e-6]}')
