# Placements for the-arena-of-loops.tex, written as a TikZ snippet (arena-chips.tex).
# Every row of the page draft's arena table (§ The arena) becomes one chip, placed in a zone by its
# "Where they meet" column. The script reads the draft and fails if a row is missing, doubled or mis-roled.
# Run from this folder: python3 the-arena-of-loops.py
import os, re

here = os.path.dirname(os.path.abspath(__file__))
draft = os.path.join(here, '..', '..', 'DSP in Looping Dimensions.md')

# (method as in the table, role, zone, x, y, chip text, note or None)
# zone: one | read | row | bent | push, or a border "a/b" (the chip straddles the shared edge)
P = [
  # READ TOGETHER: a product, a lattice in frequency
  ('FM, phase modulation, ring mod',          'make',   'read', 0.2,  -2.05, r'FM, phase mod,\\ring mod', 'a product: one row of the lattice'),
  ('Torus wavetable, Tᴺ scan',                'make',   'read', 0.2,  -3.45, r'Torus wavetable,\\T\textsuperscript{N} scan', 'one table: the full lattice'),
  ('Symmetric surfaces',                      'make',   'read', 5.2,  -2.05, r'Symmetric\\surfaces', 'only the (m, n) the symmetry allows'),
  ('Rank-N lattice analysis, modal analysis', 'read',   'read', 5.2,  -3.45, r'Rank-N lattice,\\modal analysis', 'the lattice read back'),
  # IN A ROW: linear, a lattice in time
  ('Combs in series, FDN reverb',             'shape',  'row',  12.6, -2.75, r'Combs in series,\\FDN reverb', 'a row or a matrix: echoes on a time lattice'),
  # BENT
  ('Allpass dispersion, stiff string',        'shape',  'bent', 0.2,  -8.45, r'Allpass dispersion,\\stiff string', 'its own filter: a stretched series'),
  # ONE LOOP: alone
  ('Wavetable oscillator',                    'make',   'one',  5.6,  -7.75, r'Wavetable\\oscillator', None),
  ('Step sequencer, LFO, looper',             'make',   'one',  5.6,  -8.85, r'Step sequencer,\\LFO, looper', 'the same loop, below pitch'),
  ('Comb, Karplus-Strong, waveguide',         'make',   'one',  5.6,  -10.25, r'Comb, Karplus-\\Strong, waveguide', 'with loss'),
  ('Negative-feedback comb, clarinet',        'make',   'one',  10.0, -7.75, r'Negative comb,\\clarinet', 'flipped: round twice (Möbius)'),
  ('Additive, modal banks',                   'make',   'one',  10.0, -9.15, r'Additive,\\modal banks', 'many loops, each alone, summed'),
  ('Pitch detection, autocorrelation',        'read',   'one',  10.0, -10.55, r'Pitch detection,\\autocorrelation', None),
  ('Linear prediction',                       'read',   'one',  5.6,  -11.45, r'Linear\\prediction', 'one loop and its filter, read back'),
  # PUSH BACK: self-sustaining, locking
  ('Bowed string, feedback network',          'make',   'push', 15.5, -8.45, r'Bowed string,\\feedback network', 'locking, jumps, hysteresis'),
  ('Phase-locked loop',                       'follow', 'push', 15.5, -10.25, r'Phase-locked\\loop', 'locks to the input'),
  # on borders
  ('Volterra distortion, dynamic convolution','shape',  'read/row', 10.55, -4.05, r'Volterra,\\dynamic conv.', None),
  ('Waveshaping (Chebyshev)',                 'shape',  'read/one', 8.2,  -5.55, r'Waveshaping\\(Chebyshev)', None),
  ('Chorus, flanger',                         'shape',  'read/bent', 1.2, -5.55, r'Chorus,\\flanger', None),
  ('Hard sync',                               'make',   'one/push', 13.85, -7.75, r'Hard\\sync', None),
]

# ---- check against the draft ----
text = open(draft, encoding='utf-8').read()
sec = text.split('## The arena', 1)[1].split('\n## ', 1)[0]
rows = [[c.strip() for c in l.strip().strip('|').split('|')] for l in sec.splitlines() if l.startswith('| ') and not l.startswith('| Role')]
table = {r[1]: r for r in rows}
assert len(rows) == 19, len(rows)
assert sorted(table) == sorted(p[0] for p in P), set(table) ^ set(p[0] for p in P)
for p in P:
    assert table[p[0]][0] == p[1], (p[0], table[p[0]][0], p[1])
    print(f'{p[2]:10s} {p[1]:6s} {p[0]:42s} meets: {table[p[0]][3]}')

# ---- write the chips ----
with open(os.path.join(here, 'arena-chips.tex'), 'w', encoding='utf-8') as f:
    f.write('% chips, generated by the-arena-of-loops.py: one per row of the arena table\n')
    for method, role, zone, x, y, label, note in P:
        border = '/' in zone
        f.write(f'\\chip{{{x},{y}}}{{{role[0].upper()}}}{{{label}}}{{{"chipb" if border else "chipz"}}}\n')
        if note:
            f.write(f'\\node[chipnote] at ({x + 0.02},{y - 0.4}) {{{note}}};\n')
print('19 rows placed:', {z: sum(1 for p in P if p[2] == z) for z in dict.fromkeys(p[2] for p in P)})
