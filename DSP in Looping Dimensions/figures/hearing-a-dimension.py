# Geometry and data for hearing-a-dimension.tex: one, two, three, four loops, each a picture and a spectrum.
#   had-mesh.tex, had-path.tex   torus and a golden-ratio path filling it (projection as gen-loops.py)
#   had-cube.tex                 the 3-torus: a cube whose opposite faces are glued, a straight path wrapping through it
#   had-1.dat .. had-4.dat       lines at m1 f1 + m2 f2 + ... with sum |m_i| <= 4, on one axis (frequency / f1)
#   had-counts.tex               the line counts, so the figure prints only what this script computed
# Rates: f1, phi f1, sqrt2 f1, sqrt3 f1. 1, phi, sqrt2, sqrt3 are linearly independent over the rationals,
# so no two lattice points land on the same frequency (checked below).
# Run from this folder: python3 hearing-a-dimension.py
import math, itertools
phi = (1 + 5 ** 0.5) / 2
RATES = [1.0, phi, 2 ** 0.5, 3 ** 0.5]
ORDER, TOP = 4, 5.25

# ---------- torus (two loops) ----------
R, r, elev = 1.75, 0.68, math.radians(32)

def proj(u, v):
    x = (R + r * math.cos(v)) * math.cos(u)
    y = (R + r * math.cos(v)) * math.sin(u)
    z = r * math.sin(v)
    return x, y * math.cos(elev) + z * math.sin(elev)

def visible(u, v):
    ny, nz = math.cos(v) * math.sin(u), math.sin(v)
    return (-ny * math.sin(elev) + nz * math.cos(elev)) > 0

def segments(points):
    runs, cur, vis = [], [], None
    for X, Y, v in points:
        if vis is None or v == vis:
            cur.append((X, Y))
        else:
            cur.append((X, Y)); runs.append((vis, cur)); cur = [(X, Y)]
        vis = v
    if cur: runs.append((vis, cur))
    return runs

def draw(f, runs, front, back):
    for vis, pts in runs:
        style = front if vis else back
        if len(pts) < 2 or style is None: continue
        f.write(f'\\draw[{style}] ' + ' -- '.join(f'({x:.3f},{y:.3f})' for x, y in pts) + ';\n')

with open('had-mesh.tex', 'w') as f:
    f.write('% torus mesh, generated by hearing-a-dimension.py\n')
    for k in range(24):
        u = 2 * math.pi * k / 24
        draw(f, segments([(*proj(u, 2 * math.pi * i / 80), visible(u, 2 * math.pi * i / 80)) for i in range(81)]), 'mesh', None)
    for k in range(8):
        v = 2 * math.pi * k / 8
        draw(f, segments([(*proj(2 * math.pi * i / 160, v), visible(2 * math.pi * i / 160, v)) for i in range(161)]), 'mesh', None)

TURNS = 8
with open('had-path.tex', 'w') as f:
    f.write(f'% u = t, v = phi t for {TURNS} turns, generated by hearing-a-dimension.py\n')
    pts = []
    for i in range(4001):
        t = 2 * math.pi * TURNS * i / 4000
        pts.append((*proj(t, phi * t), visible(t, phi * t)))
    draw(f, segments(pts), 'scan', 'scanback')

# ---------- cube (three loops) ----------
S, DX, DY = 2.5, 0.42, 0.30          # side, oblique depth offsets per unit depth

def P(x, y, z):
    return (S * (x + DX * z), S * (y + DY * z))

def pt(p):
    return f'({p[0]:.3f},{p[1]:.3f})'

d = (RATES[0], RATES[1], RATES[2])   # the path's direction: the three rates
p = [0.08, 0.05, 0.12]
SEGS = 9
segs = []
for _ in range(SEGS):
    # time to the next face along each axis
    ts = [(1 - p[i]) / d[i] for i in range(3)]
    t = min(ts); k = ts.index(t)
    q = [p[i] + d[i] * t for i in range(3)]
    segs.append((tuple(p), tuple(q)))
    p = [c % 1.0 if i != k else 0.0 for i, c in enumerate(q)]
with open('had-cube.tex', 'w') as f:
    f.write('% the 3-torus as a cube with opposite faces glued; generated by hearing-a-dimension.py\n')
    V = {(i, j, k): P(i, j, k) for i in (0, 1) for j in (0, 1) for k in (0, 1)}
    hidden = (0, 0, 1)                   # the far bottom-left corner
    for a, b in itertools.combinations(V, 2):
        if sum(x != y for x, y in zip(a, b)) != 1: continue
        style = 'cubeback' if hidden in (a, b) else 'cube'
        f.write(f'\\draw[{style}] {pt(V[a])} -- {pt(V[b])};\n')
    # matching arrows: each pair of glued faces carries the same mark, pointing the same way
    marks = [  # (face centre point, direction of the arrow in that face, arrow style)
        ((0, 0.5, 0.5), (0, 1, 0), 'glue1'), ((1, 0.5, 0.5), (0, 1, 0), 'glue1'),     # left = right: one head, up
        ((0.22, 0, 0.5), (0, 0, 1), 'glue2'), ((0.22, 1, 0.5), (0, 0, 1), 'glue2'),   # bottom = top: two heads, inward
        ((0.62, 0.1, 0), (1, 0, 0), 'glue3'), ((0.62, 0.1, 1), (1, 0, 0), 'glue3'),   # front = back: three heads, right
    ]
    for c, v, st in marks:
        h = 0.32 if v[2] else 0.17          # depth is foreshortened, so depth arrows run longer
        a = [c[i] - h * v[i] for i in range(3)]; b = [c[i] + h * v[i] for i in range(3)]
        f.write(f'\\draw[{st}] {pt(P(*a))} -- {pt(P(*b))};\n')
    for a, b in segs:
        f.write(f'\\draw[path3] {pt(P(*a))} -- {pt(P(*b))};\n')
        f.write(f'\\fill[ink] {pt(P(*a))} circle (0.9pt); \\fill[ink] {pt(P(*b))} circle (0.9pt);\n')

# ---------- spectra ----------
counts = []
for nloops in (1, 2, 3, 4):
    rates = RATES[:nloops]
    lines = []
    for ms in itertools.product(range(-ORDER, ORDER + 1), repeat=nloops):
        o = sum(abs(m) for m in ms)
        if o == 0 or o > ORDER: continue
        fr = sum(m * f for m, f in zip(ms, rates))
        if 0.05 < fr < TOP:
            lines.append((fr, 0.62 ** (o - 1), ms))
    lines.sort()
    gaps = [b[0] - a[0] for a, b in zip(lines, lines[1:])]
    assert min(gaps) > 1e-9, 'two lattice points share a frequency'
    with open(f'had-{nloops}.dat', 'w') as f:
        f.write('freq amp\n')
        for fr, a, _ in lines:
            f.write(f'{fr:.4f} {a:.4f}\n')
    counts.append(len(lines))
    print(f'{nloops} loop(s): {len(lines)} lines below {TOP} f1; closest pair {min(gaps) if gaps else float("nan"):.4f} f1 apart')
with open('had-counts.tex', 'w') as f:
    f.write('% line counts below the axis top, generated by hearing-a-dimension.py\n')
    for name, c in zip(('One', 'Two', 'Three', 'Four'), counts):
        f.write(f'\\def\\count{name}{{{c}}}\n')
print('cube segments', len(segs))
